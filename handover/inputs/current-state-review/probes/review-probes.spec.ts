import {test,expect} from '@playwright/test';
import {writeFileSync} from 'node:fs';
import {resolve} from 'node:path';
const output=resolve('../..');
const body=(name:string,id:string)=>({request_id:id,name,aliases:[],description:'clinical images software surgical planning'});
test('review probe: delayed save switches edit identity and overwrites another draft on next save',async({page})=>{
 const a=await (await page.request.post('/api/intake/drafts',{data:body('Review fixture A','review-race-a')})).json();
 const b=await (await page.request.post('/api/intake/drafts',{data:body('Review fixture B','review-race-b')})).json();
 await page.goto('/');await page.getByRole('button',{name:'Add venture',exact:true}).click();
 await page.getByRole('button',{name:'Review fixture A · revision 1',exact:true}).click();
 await page.getByLabel('Description',{exact:true}).fill('A revised description');
 let release:()=>Promise<void>=async()=>{};let notify:()=>void=()=>{};const held=new Promise<void>(r=>notify=r);
 await page.route('**/api/intake/drafts/'+a.draft_id+'/revisions',async route=>{
  const response=await route.fetch();release=async()=>{await route.fulfill({response});};notify();
 });
 await page.getByRole('button',{name:'Save revision',exact:true}).click();await held;
 await page.getByRole('button',{name:'Review fixture B · revision 1',exact:true}).click();
 await expect(page.getByLabel('Venture or project name')).toHaveValue('Review fixture B');
 await release();await expect(page.getByRole('heading',{name:'Saved: Review fixture A',exact:true})).toBeVisible();
 await expect(page.getByLabel('Venture or project name')).toHaveValue('Review fixture B');
 await page.unroute('**/api/intake/drafts/'+a.draft_id+'/revisions');
 const next=page.waitForResponse(r=>r.url().includes('/revisions')&&r.request().method()==='POST');
 await page.getByRole('button',{name:'Save revision',exact:true}).click();expect((await next).status()).toBe(200);
 const aAfter=await (await page.request.get('/api/intake/drafts/'+a.draft_id)).json();
 const bAfter=await (await page.request.get('/api/intake/drafts/'+b.draft_id)).json();
 expect(aAfter.content.name).toBe('Review fixture B');expect(aAfter.revision_number).toBe(3);expect(bAfter.revision_number).toBe(1);
 writeFileSync(resolve(output,'intake-race-probe.json'),JSON.stringify({observed_bug:true,original_A:a.draft_id,original_B:b.draft_id,latest_A_name:aAfter.content.name,latest_A_revision:aAfter.revision_number,B_revision:bAfter.revision_number},null,2));
});
test('review probe: reload preserves fields but loses existing draft identity',async({page})=>{
 const a=await (await page.request.post('/api/intake/drafts',{data:body('Review reload fixture','review-reload-a')})).json();
 await page.goto('/');await page.getByRole('button',{name:'Add venture',exact:true}).click();
 await page.getByRole('button',{name:'Review reload fixture · revision 1',exact:true}).click();
 await page.getByLabel('Description',{exact:true}).fill('Unsaved edit to existing draft');
 await page.reload();await page.getByRole('button',{name:'Add venture',exact:true}).click();
 await expect(page.getByLabel('Venture or project name')).toHaveValue('Review reload fixture');
 await expect(page.getByRole('button',{name:'Save draft',exact:true})).toBeVisible();
 const saved=page.waitForResponse(r=>r.url().endsWith('/api/intake/drafts')&&r.request().method()==='POST');
 await page.getByRole('button',{name:'Save draft',exact:true}).click();const newDraft=await (await saved).json();
 expect(newDraft.draft_id).not.toBe(a.draft_id);
 const old=await (await page.request.get('/api/intake/drafts/'+a.draft_id)).json();expect(old.revision_number).toBe(1);
 writeFileSync(resolve(output,'intake-reload-probe.json'),JSON.stringify({observed_bug:true,original_draft:a.draft_id,new_duplicate_draft:newDraft.draft_id,original_revision:old.revision_number},null,2));
});
