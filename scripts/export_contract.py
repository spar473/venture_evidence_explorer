#!/usr/bin/env python3
"""Generate OpenAPI and TypeScript together; --check refuses schema drift."""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from backend.main import create_app


def typescript(node):
    if node == {}:
        return "unknown"  # Explicit unconstrained JSON payload, never silently any.
    if '$ref' in node:
        return node['$ref'].rsplit('/', 1)[-1]
    if 'const' in node:
        return json.dumps(node['const'])
    if 'enum' in node:
        return ' | '.join(json.dumps(v) for v in node['enum'])
    for union in ('anyOf', 'oneOf'):
        if union in node:
            return '(' + ' | '.join(typescript(v) for v in node[union]) + ')'
    kind = node.get('type')
    if kind == 'array':
        if 'prefixItems' in node:
            return '[' + ', '.join(typescript(item) for item in node['prefixItems']) + ']'
        return '(' + typescript(node['items']) + ')[]'
    if kind == 'object' or 'properties' in node:
        required = set(node.get('required', []))
        fields = [
            json.dumps(name) + ('' if name in required else '?') + ': ' + typescript(schema)
            for name, schema in node.get('properties', {}).items()
        ]
        extra = node.get('additionalProperties')
        if isinstance(extra, dict):
            fields.append('[key: string]: ' + typescript(extra))
        return '{ ' + '; '.join(fields) + ' }'
    if kind in ('integer', 'number'):
        return 'number'
    if kind == 'null':
        return 'null'
    if kind in ('string', 'boolean'):
        return kind
    raise ValueError('Unsupported contract schema: ' + repr(node))


def generated():
    schema = create_app().openapi()
    api = json.dumps(schema, ensure_ascii=False, sort_keys=True, indent=2) + '\n'
    ts = '// Generated by python scripts/export_contract.py. Do not edit.\n'
    for name, model in sorted(schema['components']['schemas'].items()):
        ts += 'export type ' + name + ' = ' + typescript(model) + ';\n'
    return {ROOT / 'schema/openapi.json': api, ROOT / 'frontend/src/api-schema.ts': ts}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    changed = []
    for path, content in generated().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                changed.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if changed:
        raise SystemExit('Contract drift: regenerate with python scripts/export_contract.py: ' + ', '.join(changed))
    print(
        'PASS: OpenAPI and generated TypeScript match'
        if args.check
        else 'Generated schema/openapi.json and frontend/src/api-schema.ts'
    )


if __name__ == '__main__':
    main()
