#!/usr/bin/env python3
"""Validate/dry-run a research packet; --apply explicitly imports into local SQLite."""
import argparse
from datetime import date
import json
from pathlib import Path
import sys

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))
from backend.research_adapter import EXAMPLE, dry_run_research, import_research


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--input',type=Path,default=EXAMPLE)
    parser.add_argument('--db',type=Path)
    parser.add_argument('--as-of',default=date.today().isoformat())
    parser.add_argument('--mapping-decisions',type=Path,help='Explicit supplied identity-mappings:1 sidecar; never generated by the adapter.')
    parser.add_argument('--apply',action='store_true')
    parser.add_argument('--report',type=Path,help='Save exhaustive field/collection accounting as JSON.')
    args=parser.parse_args()
    try:
        if args.apply and args.db is None:
            parser.error('--apply requires --db')
        if args.apply:
            result=import_research(args.db,args.input,as_of=args.as_of,mapping_decisions_path=args.mapping_decisions)
        else:
            result=dry_run_research(args.input,args.db,as_of=args.as_of,mapping_decisions_path=args.mapping_decisions)
    except (ValueError,OSError) as error:
        result={'status':'rejected','errors':[{'path':'/','message':str(error)}],'writes':0}
    output=json.dumps(result,ensure_ascii=False,indent=2,allow_nan=False)+'\n'
    if args.report:
        args.report.parent.mkdir(parents=True,exist_ok=True)
        args.report.write_text(output)
        summary={k:v for k,v in result.items() if k!='accounting'}
        if 'accounting' in result:
            summary['accounting']={k:v for k,v in result['accounting'].items() if k!='fields'}
        summary['report']=str(args.report)
        print(json.dumps(summary,ensure_ascii=False,indent=2))
    else:
        print(output,end='')
    return 2 if result['status']=='rejected' else 0


if __name__=='__main__':
    raise SystemExit(main())
